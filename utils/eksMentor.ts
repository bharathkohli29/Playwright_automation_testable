import * as fs from 'fs';
import * as path from 'path';
import { liveDiagnosis } from './eksDiagnose';
import { ensureEksModel } from './eksModel';
import { ollamaUrl } from './ollamaHost';

export interface EksAiDiagnosis {
  summary?: string;
  rootCause?: string;
  evidence?: string;
  owner?: string;
  suggestedFix?: string;
  remediation?: string;
  verdict?: string;
  action?: string;
  acceptance?: string;
  state?: string;
  /** 'report' = parsed from a ready analyze.py report (built from real QA EKS log lines); 'model' = the model answered a question that carried no log lines */
  source?: 'report' | 'model' | 'live';
}

const OLLAMA_HOST = ollamaUrl();
const MODEL_NAME = process.env.OLLAMA_QA_MODEL || 'qa-eks-mentor-trained:latest';
// folders whose reports\ holds the ready analyze.py reports (<tool>-<first 8 chars of the run id>.md): EKS_MENTOR_DIR, the project's own qa-eks-mentor\ (where analyze.py writes)
const MENTOR_DIRS = [process.env.EKS_MENTOR_DIR, path.join(__dirname, '..', 'qa-eks-mentor')].filter((d): d is string => !!d);

function reportPaths(tool: string, runId: string): string[] {
  const short = runId.split('-')[0];
  return MENTOR_DIRS.map((d) => path.join(d, 'reports', `${tool}-${short}.md`));
}

/** The analysis files analyze.py wrote for this tool and run (the Markdown report and the Analysis_Report PDF), wherever they are. */
export function eksReportFiles(tool: string, runId: string): string[] {
  const short = runId.split('-')[0];
  const out: string[] = [];
  for (const d of MENTOR_DIRS) for (const n of [`${tool}-${short}.md`, `Analysis_Report_${tool}-${short}.pdf`]) { const p = path.join(d, 'reports', n); if (fs.existsSync(p) && !out.some((x) => path.basename(x) === n)) out.push(p); }
  return out;
}

/** True when a ready report for this tool and run exists (so analyze.py does not have to run again). */
export function eksReportExists(tool: string, runId: string): boolean {
  return reportPaths(tool, runId).some((p) => fs.existsSync(p));
}

/**
 * Checks if a pre-existing mentor report markdown file exists on disk.
 */
function readLocalReport(tool: string, runId: string): string | null {
  for (const reportPath of reportPaths(tool, runId)) {
    if (!fs.existsSync(reportPath)) continue;
    try {
      return fs.readFileSync(reportPath, 'utf8');
    } catch {
      return null;
    }
  }
  return null;
}

/**
 * Parses markdown report generated by analyze.py / qa-eks-mentor into structured fields.
 * Supports both RCA_PROMPT.md template and legacy 8-section reports.
 */
export function parseReportMarkdown(md: string): EksAiDiagnosis {
  const diag: EksAiDiagnosis = {};

  // Check for "No RCA needed" (Rule 8)
  if (/no rca needed:\s*the tool produced output/i.test(md)) {
    diag.verdict = 'Tool produced output';
    diag.summary = 'No RCA needed: the tool produced output.';
    diag.rootCause = 'Tool produced output.';
    return diag;
  }

  // Check for new RCA template (RCA_PROMPT.md Section 1)
  const rcaHeaderM = md.match(/^RCA:\s*([^\n-]+)\s*-\s*([^\n]+)/im);
  const verdictRcaM = md.match(/^Verdict:\s*([^\n]+)/im);
  const rootCauseRcaM = md.match(/^Root cause:\s*([^\n]+)/im);
  const evidenceRcaM = md.match(/^Evidence:\s*\n((?:\s*-\s*[^\n]+\n?)+)/im);
  const ownerRcaM = md.match(/^Owner:\s*([^\n]+)/im);
  const actionRcaM = md.match(/^Action:\s*([^\n]+)/im);
  const acceptanceRcaM = md.match(/^Acceptance:\s*([^\n]+)/im);

  if (verdictRcaM || rootCauseRcaM) {
    if (rcaHeaderM) diag.state = rcaHeaderM[2].trim();
    if (verdictRcaM) diag.verdict = verdictRcaM[1].trim();
    if (rootCauseRcaM) {
      diag.rootCause = rootCauseRcaM[1].trim();
      diag.summary = diag.rootCause;
    }
    if (evidenceRcaM) {
      const lines = evidenceRcaM[1].trim().split('\n').map((l) => l.replace(/^-\s*/, '').trim()).filter(Boolean);
      diag.evidence = lines.join('; ');
    } else {
      // the model may also answer "Evidence: <one line>" on the same line (the trained format is the bullet list)
      const inline = md.match(/^Evidence:[ \t]*([^\n]+)/im);
      if (inline) diag.evidence = inline[1].trim();
    }
    if (ownerRcaM) diag.owner = ownerRcaM[1].trim();
    if (actionRcaM) {
      diag.action = actionRcaM[1].trim();
      diag.suggestedFix = diag.action;
    }
    if (acceptanceRcaM) diag.acceptance = acceptanceRcaM[1].trim();

    return diag;
  }

  // Fallback to legacy markdown format (## 1. Summary, ## 4. Root Cause ...)
  const summaryMatch = md.match(/## 1\. Summary\s+([\s\S]*?)(?=\n## 2|\n#|$)/i);
  if (summaryMatch) diag.summary = summaryMatch[1].trim();

  const evidenceMatch = md.match(/## 3\. Evidence from QA EKS\s+([\s\S]*?)(?=\n## 4|$)/i);
  if (evidenceMatch) {
    const lines = evidenceMatch[1].trim().split('\n').filter((l) => l.trim().startsWith('-'));
    if (lines.length) diag.evidence = lines[0].replace(/^-\s*/, '').trim();
  }

  const causeMatch = md.match(/## 4\. Root Cause\s+([\s\S]*?)(?=\n## 5|$)/i);
  if (causeMatch) diag.rootCause = causeMatch[1].trim();

  const fixMatch = md.match(/## 6\. Recommended Fix\s+([\s\S]*?)(?=\n## 7|$)/i);
  if (fixMatch) {
    const text = fixMatch[1].trim();
    const ownerM = text.match(/\*\*Owner:\*\*\s*(.*)/i);
    const actionM = text.match(/\*\*Action:\*\*\s*(.*)/i);
    if (ownerM) diag.owner = ownerM[1].trim();
    if (actionM) {
      diag.suggestedFix = actionM[1].trim();
      diag.action = diag.suggestedFix;
    }
  }

  const verdictM = md.match(/\*\*Verdict:\*\*\s*([^\s*]+)/i);
  if (verdictM) diag.verdict = verdictM[1].trim();

  return diag;
}

/**
 * Queries the local fine-tuned Ollama model directly via REST API.
 */
async function queryOllamaDirect(prompt: string, timeoutMs = 45_000): Promise<string | null> {
  if (!(await ensureEksModel())) return null;
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), timeoutMs);

  try {
    const res = await fetch(`${OLLAMA_HOST}/api/chat`, {
      method: 'POST',
      signal: controller.signal,
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        model: MODEL_NAME,
        stream: false,
        options: {
          temperature: 0.1,
          num_ctx: 4096,
        },
        messages: [
          {
            role: 'user',
            content: prompt,
          },
        ],
      }),
    });

    if (!res.ok) return null;
    const json = await res.json();
    return json?.message?.content?.trim() || null;
  } catch {
    return null; // Gracefully return null if Ollama is offline or timed out
  } finally {
    clearTimeout(timeout);
  }
}

/**
 * Main entry point: Retrieves AI-powered EKS defect diagnosis for a tool & run.
 * Conforms to RCA_PROMPT.md specification.
 * Safe and non-blocking: never throws; falls back to null if anything is offline.
 */
export async function getEksAiDiagnosis(
  tool: string,
  runId: string,
  context?: {
    branch?: string;
    version?: string;
    repo?: string;
    observed?: string;
    note?: string;
    branchDir?: string;
    state?: 'NOT_TRIGGERED' | 'EMPTY' | 'FAILED' | 'SKIPPED' | 'OUTPUT';
    language?: string;
    s3?: string;
    logEvidence?: string;
    podState?: string;
  }
): Promise<EksAiDiagnosis | null> {
  // 1. Check local pre-generated report in mentor/reports/
  const localMd = readLocalReport(tool, runId);
  if (localMd) {
    return { ...parseReportMarkdown(localMd), source: 'report' };
  }

  // 2. Real log lines captured live from the QA EKS pods during this run (eks-live/): the model explains ONLY those lines
  if (context?.branchDir) {
    const live = await liveDiagnosis(tool, runId, context.branchDir, { observed: context.observed, note: context.note, version: context.version });
    if (live) return live;
  }

  // 3. Query Ollama directly with an RCA input block (RCA_PROMPT.md)
  // 2. Determine state according to RCA_PROMPT.md specification
  let state = context?.state;
  if (!state) {
    const obs = (context?.observed || '').toLowerCase();
    if (obs.includes('not triggered') || obs.includes('not_triggered') || obs.includes('no folder')) {
      state = 'NOT_TRIGGERED';
    } else if (obs.includes('empty') || obs.includes('[]') || obs.includes('{}') || obs.includes('all zeros')) {
      state = 'EMPTY';
    } else if (obs.includes('fail')) {
      state = 'FAILED';
    } else if (obs.includes('skip') || obs.includes('not applicable')) {
      state = 'SKIPPED';
    } else {
      state = 'NOT_TRIGGERED';
    }
  }

  const lang = context?.language || (context?.version ? `node ${context.version}` : 'unknown');
  const branch = context?.branch || 'unknown';
  const s3 = context?.s3 || (context?.observed ? context.observed : 'no folder');
  const logEvidence = context?.logEvidence || (context?.note ? context.note : 'none');
  const podState = context?.podState || 'all Running, 0 restarts';

  // Format matching Section 2 (Input block) of RCA_PROMPT.md
  const prompt = [
    'INPUT',
    `TOOL: ${tool}`,
    `STATE: ${state}`,
    `LANGUAGE: ${lang}`,
    `BRANCH: ${branch}   RUN: ${runId}`,
    `S3: ${s3}`,
    `LOG EVIDENCE:`,
    logEvidence,
    `POD STATE: ${podState}`,
  ].join('\n');

  const responseText = await queryOllamaDirect(prompt);
  if (responseText) {
    return { ...parseReportMarkdown(responseText), source: 'model' };
  }

  return null;
}
