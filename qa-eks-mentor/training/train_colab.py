"""
=================================================================================
STEP-BY-STEP LLM FINE-TUNING TUTORIAL FOR GOOGLE COLAB (FREE T4 GPU)
=================================================================================
This script fine-tunes Qwen 2.5 / Qwen 3 using Unsloth (QLoRA) on your QA dataset
and exports a quantized GGUF file directly ready for Ollama.

How to run:
1. Open https://colab.research.google.com
2. Change Runtime to 'T4 GPU' (Runtime -> Change runtime type -> T4 GPU)
3. Upload this script and your 'dataset.jsonl'
4. Run each section.
=================================================================================
"""

# -------------------------------------------------------------------------
# STEP 1: Install Unsloth and Required Libraries (Run in Colab cell)
# -------------------------------------------------------------------------
# !pip install "unsloth[colab-new] @ git+https://github.com/unslothai/unsloth.git"
# !pip install --no-deps trl peft accelerate bitsandbytes

# -------------------------------------------------------------------------
# STEP 2: Load the Base Model in 4-bit Quantization (QLoRA)
# -------------------------------------------------------------------------
from unsloth import FastLanguageModel
import torch

max_seq_length = 2048  # Maximum length of prompt + response
dtype = None           # None = Auto-detect (Float16 or Bfloat16)
load_in_4bit = True    # 4-bit reduces VRAM usage from 16GB down to ~4-6GB!

# We load Qwen (or any base model supported by Ollama)
model, tokenizer = FastLanguageModel.from_pretrained(
    model_name="Qwen/Qwen2.5-3B-Instruct",  # Or unsloth/Qwen2.5-7B-Instruct
    max_seq_length=max_seq_length,
    dtype=dtype,
    load_in_4bit=load_in_4bit,
)

# -------------------------------------------------------------------------
# STEP 3: Attach LoRA (Low-Rank Adaptation) Adapters
# -------------------------------------------------------------------------
# What is LoRA? Instead of modifying all 3 Billion weights, LoRA adds small
# trainable "adapter" matrices (only ~1-2% of total parameters).
# This makes training 10x faster and uses much less memory.
model = FastLanguageModel.get_peft_model(
    model,
    r=16,          # Rank: Higher = more expressive, Lower = faster/lighter
    target_modules=["q_proj", "k_proj", "v_proj", "o_proj",
                    "gate_proj", "up_proj", "down_proj"],
    lora_alpha=16,
    lora_dropout=0, # Optimized = 0
    bias="none",
    use_gradient_checkpointing="unsloth",
    random_state=3407,
)

# -------------------------------------------------------------------------
# STEP 4: Format and Load Your Training Dataset
# -------------------------------------------------------------------------
from datasets import load_dataset

# Load your custom dataset generated by prepare_dataset.py
dataset = load_dataset("json", data_files="dataset.jsonl", split="train")

def format_prompts(batch):
    texts = []
    for messages in batch["messages"]:
        # Converts chat messages into standard Qwen ChatML string
        text = tokenizer.apply_chat_template(messages, tokenize=False, add_generation_prompt=False)
        texts.append(text)
    return {"text": texts}

dataset = dataset.map(format_prompts, batched=True)

# -------------------------------------------------------------------------
# STEP 5: Configure and Run the Trainer
# -------------------------------------------------------------------------
from trl import SFTTrainer
from transformers import TrainingArguments

trainer = SFTTrainer(
    model=model,
    tokenizer=tokenizer,
    train_dataset=dataset,
    dataset_text_field="text",
    max_seq_length=max_seq_length,
    dataset_num_proc=2,
    packing=False, # False for short QA reports
    args=TrainingArguments(
        per_device_train_batch_size=2,
        gradient_accumulation_steps=4,
        warmup_steps=5,
        max_steps=60,            # Adjust according to dataset size (e.g., 50-100)
        learning_rate=2e-4,       # Standard learning rate for LoRA
        fp16=not torch.cuda.is_bf16_supported(),
        bf16=torch.cuda.is_bf16_supported(),
        logging_steps=1,
        optim="adamw_8bit",       # Memory-efficient optimizer
        weight_decay=0.01,
        lr_scheduler_type="linear",
        seed=3407,
        output_dir="outputs",
    ),
)

print("Starting training...")
trainer.train()
print("Training completed!")

# -------------------------------------------------------------------------
# STEP 6: Export Directly to GGUF for Ollama
# -------------------------------------------------------------------------
# Unsloth can automatically merge the LoRA adapters into the base model
# and export a quantized GGUF file in one single command!

model.save_pretrained_gguf(
    "qa-eks-mentor-trained",
    tokenizer,
    quantization_method="q4_k_m"  # Standard Ollama 4-bit quantization
)

print("GGUF exported! Download 'qa-eks-mentor-trained-q4_k_m.gguf' and move to ")

